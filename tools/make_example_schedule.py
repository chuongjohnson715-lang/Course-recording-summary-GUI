"""生成示例课表 课表.example.xls。

用途：让 clone 本项目的人也能跑通「按课表自动改名」功能，
      而不必把自己的真实课表传上来。

格式必须与真实课表一致（core/schedule.py 按固定结构解析）：
  * 第 3 行（index 2）：第 1 列起为 星期一~星期日
  * 第 4 行起：第 1 列为 "第N大节\\nXX、XX小节\\nHH:MM~HH:MM"
  * 课程格：课程名行 + "教师;周次周;节次" 行，可再接一行教室（含"楼/室/线上"会被跳过）

注意：本文件全部为虚构数据，与任何真实学校/教师/学生无关。

运行：
    .venv\\Scripts\\python.exe tools\\make_example_schedule.py
"""
from __future__ import annotations

from pathlib import Path

import xlwt

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "课表.example.xls"

WEEKDAYS = ["星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日"]

# 一天 5 个大节；时间段与真实课表保持同样的写法，方便解析器识别
SLOTS = [
    ("第一大节", "01、02小节", "08:00~09:50"),
    ("第二大节", "03、04小节", "10:10~12:00"),
    ("第三大节", "05、06小节", "14:00~15:50"),
    ("第四大节", "07、08小节", "16:10~18:00"),
    ("第五大节", "09、10小节", "19:00~20:50"),
]

# 虚构课表：{(大节 index, 星期 index): 单元格文本}
# 星期 index: 0=星期一 ... 6=星期日
CELLS: dict[tuple[int, int], str] = {
    # ---- 第一大节 ----
    (0, 0): "高等数学A\n李示例;1-16周;1-2节\n1号楼(A101室)\n",
    (0, 2): "线性代数\n王示例;1-8周;1-2节\n1号楼(A203室)\n"
            "概率论与数理统计\n赵示例;9-16周;1-2节\n1号楼(A203室)\n",
    (0, 4): "大学英语（读写）\n陈示例;1-16周;1-2节\n外语楼(E305室)\n",

    # ---- 第二大节 ----
    (1, 0): "程序设计基础\n刘示例;1-12周;3-4节\n计算机楼(C401室)\n",
    (1, 2): "数据结构\n孙示例;1-16周;3-4节\n计算机楼(C402室)\n",
    (1, 3): "大学物理（示例）\n周示例;1-14周;3-4节\n理科楼(P108室)\n",
    (1, 4): "数据库原理\n吴示例;5-16周;3-4节\n计算机楼(C403室)\n",

    # ---- 第三大节 ----
    (2, 1): "操作系统\n郑示例;1-16周;5-6节\n计算机楼(C404室)\n",
    (2, 3): "计算机网络\n冯示例;1-12周;5-6节\n计算机楼(C405室)\n"
            "计算机组成原理\n蒋示例;13-16周;5-6节\n计算机楼(C405室)\n",
    (2, 4): "体育（示例）\n韩示例;1-16周;5-6节\n体育馆(GYM-1室)\n",

    # ---- 第四大节 ----
    (3, 0): "思想道德与法治\n杨示例;1-8周;7-8节\n文科楼(L201室)\n",
    (3, 2): "人工智能导论\n徐示例;6-16周;7-8节\n计算机楼(C406室)\n",
    (3, 3): "软件工程\n朱示例;1-10周;7-8节\n计算机楼(C407室)\n",

    # ---- 第五大节（含一门线上课，用来验证"线上"行会被跳过）----
    (4, 1): "创新创业基础\n何示例;3-12周;9-10节\n0号楼(线上虚拟教室)\n",
    (4, 5): "通识选修：艺术鉴赏\n吕示例;4-13周;9-10节\n0号楼(线上虚拟教室)\n",
}


def main() -> int:
    wb = xlwt.Workbook(encoding="utf-8")
    sh = wb.add_sheet("Sheet1")

    # 第 1、2 行为说明（解析器从第 3 行开始看，这两行是给人看的）
    sh.write(0, 0, "示例大学 示例同学 学生个人课表（虚构数据，仅用于演示）")
    sh.write(
        1, 0,
        "学年学期：2026-2027-1        班级：示例班级        专业：示例专业        "
        "院系：示例学院        打印日期：2026-10-08",
    )

    # 第 3 行：星期表头
    for i, name in enumerate(WEEKDAYS):
        sh.write(2, i + 1, name)

    # 第 4 行起：各大节
    for r, (big, small, span) in enumerate(SLOTS):
        row = 3 + r
        sh.write(row, 0, f"{big}\n{small}\n{span}")
        for c in range(len(WEEKDAYS)):
            text = CELLS.get((r, c))
            if text:
                sh.write(row, c + 1, text)

    wb.save(str(OUT))
    print(f"已生成: {OUT}")
    print(f"  课程格数量: {len(CELLS)}")
    print("  全部为虚构数据（示例大学 / 李示例 等）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
